/** Generate docs/tools.md — the complete tool reference — from catalog.json. */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

interface ToolSchema {
  type?: string;
  properties?: Record<string, { type?: string; description?: string; enum?: unknown[] }>;
  required?: string[];
}

interface Tool {
  name: string;
  groups?: string[];
  description: string;
  inputSchema?: ToolSchema;
}

interface Catalog {
  version: string;
  tools: Tool[];
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(path.join(root, "catalog.json"), "utf8")) as Catalog;

const tools = [...catalog.tools].sort((a, b) => a.name.localeCompare(b.name));

const lines: string[] = [
  "# Tool reference",
  "",
  `\`@fraziym/mcp@${catalog.version}\` — **${tools.length} tools** in one process. Regenerated by \`npm run docs\`; source of truth is \`catalog.json\` (build-time, no tool family is imported to answer \`tools/list\`).`,
  "",
  "## Index",
  "",
  "| Tool | Description |",
  "| --- | --- |",
];

for (const tool of tools) {
  const desc = tool.description.replace(/\|/g, "\\|");
  lines.push(`| [\`${tool.name}\`](#${tool.name.replace(/_/g, "-")}) | ${desc} |`);
}

for (const tool of tools) {
  lines.push("", `## \`${tool.name}\``, "", tool.description, "");
  const props = tool.inputSchema?.properties ?? {};
  const required = new Set(tool.inputSchema?.required ?? []);
  const keys = Object.keys(props);
  if (keys.length === 0) {
    lines.push("No parameters.", "");
    continue;
  }
  lines.push("| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |");
  for (const key of keys) {
    const p = props[key];
    const desc = (p.description ?? "").replace(/\|/g, "\\|");
    lines.push(`| \`${key}\` | ${p.type ?? "any"} | ${required.has(key) ? "yes" : "no"} | ${desc} |`);
  }
  lines.push("");
}

mkdirSync(path.join(root, "docs"), { recursive: true });
writeFileSync(path.join(root, "docs", "tools.md"), lines.join("\n"));
console.log(`docs/tools.md — ${tools.length} tools`);
